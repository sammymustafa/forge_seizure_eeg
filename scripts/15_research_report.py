def section_limitations() -> list[str]:
    return [
        "## 9. Limitations",
        "",
        "1. **Simulated versus real wearables.** The CHB-MIT configurations "
        "are scalp-position proxies. Contact material, skin coupling, "
        "reference placement, motion artefact and amplifier noise all differ "
        "in a real device. The two datasets' results are never pooled.",
        "2. **No paired comparison in SeizeIT2.** The public release has no "
        "simultaneous full-scalp recording, so the full-versus-wearable "
        "question cannot be answered there at all.",
        "3. **Placement confound.** SeizeIT2 sensors were positioned with "
        "reference to the suspected onset zone, so anatomy and placement are "
        "entangled in every subgroup in §8.",
        "4. **Overlapping intervals are not equivalence.** Several reduced "
        "configurations have confidence intervals that include zero "
        "difference from full scalp. With 23 patients the study cannot "
        "resolve differences of the size that would matter clinically; that "
        "is a limit of power, not a demonstration of equivalence.",
        "5. **Offline, not causal.** Zero-phase filtering and whole-recording "
        "normalisation are retrospective. §6.3 shows the normalisation is "
        "worth more than any electrode choice, so an online equivalent is a "
        "prerequisite, not a detail.",
        "6. **Cohorts.** CHB-MIT is paediatric and single-centre. All "
        "SeizeIT2 participants have focal epilepsy, so no "
        "focal-versus-generalised comparison is possible.",
        "7. **Selected recordings in SeizeIT2.** Only recordings containing at "
        "least one annotated seizure were analysed (3 062 h of the full "
        "corpus). False-alarm rates are therefore measured on that subset, "
        "not on the whole monitoring period.",
        "8. **Subgroup sizes.** Several anatomical subgroups rest on a handful "
        "of patients; those rows are marked sparse in the figures and should "
        "be read as descriptive.",
        "",
    ]



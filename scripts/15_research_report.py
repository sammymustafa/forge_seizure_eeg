def _pretty(v):
    if isinstance(v, str):
        return PRETTY.get(v, MONTAGE_LABELS.get(v, v))
    return v


def md_table(df: pd.DataFrame, cols: list[str], headers: list[str],
             rounder: dict | None = None) -> str:
    d = df[cols].copy()
    for c in d.columns:
        if not pd.api.types.is_numeric_dtype(d[c]):
            d[c] = d[c].map(_pretty)
    if rounder:
        for c, n in rounder.items():
            if c in d:
                d[c] = d[c].astype(float).round(n)
    head = "| " + " | ".join(headers) + " |\n"
    head += "|" + "|".join("---" for _ in headers) + "|\n"
    body = "\n".join(
        "| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |"
        for row in d.itertuples(index=False))
    return head + body + "\n"


